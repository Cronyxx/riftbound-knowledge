"""Index rule numbers in Riot's PDF without reproducing its text.

Usage: python3 scripts/index-rulebook.py /path/to/official-core-rules.pdf
Requires pypdf. Review the source URL/date in core-rules.json when updating.
"""

import hashlib
import json
import re
import sys
from pathlib import Path

from pypdf import PdfReader

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
reader = PdfReader(source)
pages = {}
for page_number, page in enumerate(reader.pages, 1):
    for match in re.finditer(r"^\s*(\d{3}(?:\.(?:\d+|[a-z]))*)\.(?=\s)", page.extract_text(), re.M):
        pages.setdefault(match[1], page_number)

metadata_path = root / "docs/reference/core-rules.json"
metadata = json.loads(metadata_path.read_text())
metadata.update(sha256=hashlib.sha256(source.read_bytes()).hexdigest(), pageCount=len(reader.pages), rules=pages)
metadata_path.write_text(json.dumps(metadata, indent=2) + "\n")

anchors = ['<!-- Generated by scripts/index-rulebook.py; keep beside the reader. -->', '<div class="rulebook-anchors" aria-hidden="true">']
anchors.extend(f'<span id="rule-{rule.replace(".", "-")}"></span>' for rule in pages)
anchors.append('</div>')
(root / "docs/reference/rule-anchors.md").write_text("\n".join(anchors) + "\n")
print(f"Indexed {len(pages)} rules across {len(reader.pages)} PDF pages.")
